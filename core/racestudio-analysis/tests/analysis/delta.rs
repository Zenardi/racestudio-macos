#[test]
fn test_delta_matches_golden() {
    let Some(session) = decoded_session() else {
        return;
    };
    let laps = segment_laps(&session);
    let g: DeltaGolden = load_golden("aim_official_test", "delta_t").expect("load delta golden");
    assert_eq!(g.file, SAMPLE);
    let reference = &laps[g.reference_index];
    let comparison = &laps[g.comparison_index];

    let series = delta_t(reference, comparison).expect("delta_t");

    assert!(series[0].1.abs() < 1e-9, "golden series starts at 0");
    for point in &g.points {
        let dt = dt_at(&series, point.distance);
        assert!(
            (dt - point.dt).abs() < 1e-3,
            "delta-t at distance {}: computed {dt} vs golden {}",
            point.distance,
            point.dt
        );
    }
}

#[test]
fn test_delta_final_matches_beacon_laptime_difference() {
    // Independent oracle: the final delta-t must equal the difference of the two
    // laps' libxrk-validated beacon durations (issue 1.5 golden). The ~0.07 s
    // slack is the GPS-sample time span (first fix → last fix) versus the beacon
    // marker duration; both laps carry a similar offset, so it nearly cancels.
    let Some(session) = decoded_session() else {
        return;
    };
    let laps = segment_laps(&session);
    let dg: DeltaGolden = load_golden("aim_official_test", "delta_t").expect("delta golden");
    let lg: LapsGolden = load_golden("aim_official_test", "laps").expect("laps golden");

    let series = delta_t(&laps[dg.reference_index], &laps[dg.comparison_index]).expect("delta_t");

    let final_dt = series.last().expect("non-empty").1;
    let beacon_diff = (lg.laps[dg.comparison_index].duration_ms
        - lg.laps[dg.reference_index].duration_ms) as f64
        / 1000.0;
    assert!(
        (final_dt - beacon_diff).abs() < 0.25,
        "final delta-t {final_dt}s vs beacon lap-time difference {beacon_diff}s"
    );
}

/// Regenerate `fixtures/golden/aim_official_test.delta_t.json` from the decoded
/// fixture. Not part of the normal run; execute with:
/// `cargo test -p racestudio-analysis --test delta_test -- --ignored generate_delta_golden`
#[test]
#[ignore = "regenerates the delta_t golden; run with --ignored"]
fn generate_delta_golden() {
    let session = decoded_session().expect("fixture required to regenerate the golden");
    let laps = segment_laps(&session);
    let reference_index = 1usize; // first flying lap (lap 0 is the out-lap)
    let comparison_index = session.laps().best_lap_index().expect("a fastest lap") as usize;

    let series = delta_t(&laps[reference_index], &laps[comparison_index]).expect("delta_t");

    // Sample ~25 evenly spaced grid points.
    let n = 25.min(series.len());
    let round6 = |x: f64| (x * 1e6).round() / 1e6;
    let points: Vec<serde_json::Value> = (0..n)
        .map(|k| {
            let idx = if n <= 1 {
                0
            } else {
                k * (series.len() - 1) / (n - 1)
            };
            let (distance, dt) = series[idx];
            serde_json::json!({ "distance": round6(distance), "dt": round6(dt) })
        })
        .collect();
    let golden = serde_json::json!({
        "file": SAMPLE,
        "reference_index": reference_index,
        "comparison_index": comparison_index,
        "point_count": points.len(),
        "points": points,
    });

    let path = fixture_path("golden").join("aim_official_test.delta_t.json");
    let mut text = serde_json::to_string_pretty(&golden).expect("serialize golden");
    text.push('\n');
    std::fs::write(&path, text).expect("write golden");
    eprintln!("wrote {}", path.display());
}
