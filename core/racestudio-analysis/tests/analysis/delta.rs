#[test]
fn test_delta_t_starts_at_zero() {
    let reference = speed_lap(0, 0.0, &[(0.0, 10.0), (1000.0, 10.0), (2000.0, 10.0)]);
    let comparison = speed_lap(1, 0.0, &[(0.0, 8.0), (1000.0, 12.0), (2000.0, 8.0)]);

    let series = delta_t(&reference, &comparison).expect("delta_t");

    assert!(!series.is_empty());
    assert_eq!(series[0].0, 0.0, "series starts at distance 0");
    assert_eq!(series[0].1, 0.0, "delta-t at distance 0 is exactly 0");
}

#[test]
fn test_delta_t_final_equals_laptime_difference() {
    // Reference covers 100 m in 10 s; comparison covers the same 100 m in 20 s.
    let reference_speed = [(0.0, 10.0), (10000.0, 10.0)];
    let comparison_speed = [(0.0, 0.0), (20000.0, 10.0)];
    let reference = speed_lap(0, 0.0, &reference_speed);
    let comparison = speed_lap(1, 0.0, &comparison_speed);

    let series = delta_t(&reference, &comparison).expect("delta_t");

    let expected = covered_time_s(&comparison_speed, 0.0) - covered_time_s(&reference_speed, 0.0);
    let final_dt = series.last().expect("non-empty").1;
    assert!(
        (final_dt - expected).abs() < 1e-6,
        "final delta-t {final_dt} should equal lap-time difference {expected}"
    );
}

#[test]
fn test_identical_laps_produce_zero_series() {
    let lap = speed_lap(
        0,
        0.0,
        &[(0.0, 10.0), (1000.0, 20.0), (2000.0, 15.0), (3000.0, 25.0)],
    );

    let series = delta_t(&lap, &lap).expect("delta_t");

    assert!(!series.is_empty());
    for (distance, dt) in &series {
        assert!(
            dt.abs() < 1e-9,
            "dt at {distance} must be 0 for identical laps"
        );
    }
}

#[test]
fn test_sign_convention_slower_is_positive() {
    // Comparison is slower everywhere (lower speed → later at each distance), so
    // delta-t must be positive.
    let reference = speed_lap(0, 0.0, &[(0.0, 20.0), (5000.0, 20.0), (10000.0, 20.0)]);
    let comparison = speed_lap(1, 0.0, &[(0.0, 10.0), (5000.0, 10.0), (20000.0, 10.0)]);

    let series = delta_t(&reference, &comparison).expect("delta_t");

    let final_dt = series.last().expect("non-empty").1;
    assert!(
        final_dt > 0.0,
        "slower comparison ⇒ positive delta-t, got {final_dt}"
    );
    assert!(
        series.iter().all(|&(_, dt)| dt >= -1e-9),
        "a uniformly slower lap never gains time"
    );
}

#[test]
fn test_empty_lap_returns_error() {
    // A lap with no GPS Speed channel cannot yield a distance axis → EmptyLap.
    let channelless = Lap::new(0, 0.0, 10.0, vec![LapChannel::new("RPM", vec![(0.0, 1.0)])]);
    let valid = speed_lap(1, 0.0, &[(0.0, 10.0), (1000.0, 10.0)]);
    assert_eq!(
        delta_t(&channelless, &valid).expect_err("channel-less reference"),
        AnalysisError::EmptyLap
    );

    // A present-but-empty speed channel is likewise empty.
    let empty = Lap::new(0, 0.0, 10.0, vec![LapChannel::new("GPS Speed", vec![])]);
    assert_eq!(
        delta_t(&empty, &valid).expect_err("empty speed channel"),
        AnalysisError::EmptyLap
    );
}

#[test]
fn test_non_monotonic_distance_returns_error() {
    // A negative speed excursion makes the faithful distance integral dip, so the
    // distance axis is not monotonic → DistanceNotMonotonic (not a panic).
    let reference = speed_lap(0, 0.0, &[(0.0, 10.0), (1000.0, -50.0), (2000.0, 10.0)]);
    let comparison = speed_lap(1, 0.0, &[(0.0, 10.0), (1000.0, 10.0)]);
    assert_eq!(
        delta_t(&reference, &comparison).expect_err("non-monotonic distance"),
        AnalysisError::DistanceNotMonotonic
    );
}

#[test]
fn test_zero_distance_reference_no_panic() {
    // A stationary reference lap (speed 0 → total distance 0) is degenerate but
    // valid (its distance axis is non-empty and non-decreasing); delta-t must not
    // divide by the zero span — it collapses to the start line without panicking.
    let stationary = speed_lap(0, 0.0, &[(0.0, 0.0), (1000.0, 0.0)]);
    let comparison = speed_lap(1, 0.0, &[(0.0, 10.0), (1000.0, 10.0)]);

    let series = delta_t(&stationary, &comparison).expect("delta_t");

    assert_eq!(series.len(), 2);
    assert!(series.iter().all(|&(_, dt)| dt.abs() < 1e-9));
}

