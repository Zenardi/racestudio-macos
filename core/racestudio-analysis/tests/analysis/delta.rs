//! Delta-t / time variance tests (issue 3.2).
//!
//! - **Property/error** (synthetic laps): the behavioural contract — starts at
//!   zero, ends at the lap-time difference, identical laps → zero, sign
//!   convention (slower ⇒ positive), and the two typed error paths. Deterministic
//!   and fixture-free.
//! - **Golden** (`test_delta_matches_golden`): reproduce the committed
//!   `delta_t` of a reference lap vs the fastest lap over the real
//!   `aim_official_test.xrk`. The `.xrk` is git-ignored (fetched by
//!   `make fixtures`); the test skips cleanly when it is absent.
//!
//! The golden is regenerated by the `#[ignore]`d `generate_delta_golden` below.

use std::path::PathBuf;

use crate::support::fixtures::{fixture_path, load_golden, DeltaGolden, LapsGolden};
use racestudio_analysis::{delta_t, segment_laps, AnalysisError, Lap, LapChannel};
use racestudio_decode::{decode_session, Session};

const SAMPLE: &str = "aim_official_test.xrk";

fn xrk_or_skip(name: &str) -> Option<PathBuf> {
    let path = fixture_path(name);
    match std::fs::read(&path) {
        Ok(bytes) if bytes.starts_with(b"<h") => Some(path),
        _ => {
            eprintln!(
                "skipping: {} is not a real .xrk sample — run `make fixtures` to fetch it",
                path.display()
            );
            None
        }
    }
}

fn decoded_session() -> Option<Session> {
    let path = xrk_or_skip(SAMPLE)?;
    Some(decode_session(&path).expect("decode session"))
}

/// A lap carrying only a `GPS Speed` channel (all delta-t needs) whose absolute
/// sample times are as given; `[start, end)` spans them.
fn speed_lap(number: u32, start_ms: f64, speed: &[(f64, f64)]) -> Lap {
    let end_ms = speed.iter().map(|&(t, _)| t).fold(start_ms, f64::max) + 1.0;
    Lap::new(
        number,
        start_ms,
        end_ms,
        vec![LapChannel::new("GPS Speed", speed.to_vec())],
    )
}

/// Last re-based sample time (seconds) — the time span the lap's samples cover.
fn covered_time_s(speed: &[(f64, f64)], start_ms: f64) -> f64 {
    (speed.last().map(|&(t, _)| t).unwrap_or(start_ms) - start_ms) / 1000.0
}

/// Linear interpolation of a `(distance, dt)` series at `distance`.
fn dt_at(series: &[(f64, f64)], distance: f64) -> f64 {
    if distance <= series[0].0 {
        return series[0].1;
    }
    for pair in series.windows(2) {
        let (d0, v0) = pair[0];
        let (d1, v1) = pair[1];
        if distance <= d1 {
            return v0 + (v1 - v0) * (distance - d0) / (d1 - d0);
        }
    }
    series[series.len() - 1].1
}

